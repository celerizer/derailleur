/**
 * Roulette hook site check
 *
 * A MP8_HOOK_W?? row addresses memory inside a board overlay, so unlike every
 * other hook in this header it is only meaningful while that board is
 * resident. Install a board's rows only when BOTH hold, and re-test them every
 * time you would write:
 *
 *   1. omcurovl (0x802CDD1C) == that board's ovl index (112..118). Outside a
 *      board it names something else entirely and the overlay is not loaded --
 *      the address then belongs to whatever else got the memory.
 *   2. the word at the site reads back as MP8_ROULETTE_ORIG, the instruction
 *      the row displaces. The overlays are loaded into a first-fit heap, so
 *      their addresses are an observation (asm/mp8/bases.txt), not something
 *      the game guarantees.
 *
 * Fail 1 and there is nothing to patch yet -- that is the normal state for
 * most of a session, not an error. Fail 2 with 1 holding means that board
 * really did load somewhere else: find the new base (asm/mp8/RUNTIME.txt),
 * put it in bases.txt and re-emit.
 *
 * Stop writing when 1 stops holding: the board unloads and the address goes
 * stale.
 *
 * Each MP8_HOOK_W?? has two rows, in this order:
 *
 *   row 0  the forced candidate list, displacing MP8_ROULETTE_ORIG
 *   row 1  the minigame skip, displacing MP8_MGCALL_ORIG
 *
 * Row 1 is independent of row 0 and of the cave -- it is a plain constant
 * swap, 97 (mginstdll) to 100 (mgresultdll), so the board calls the tail of
 * the minigame chain instead of its head. Install it alone if all you want is
 * the skip. It does not award coins; nothing in the minigame chain does. Write
 * GwPlayer[n].coin yourself:
 *
 *   GwPlayer 0x802282F8, stride 0x118, coin at +0x26 (s16)
 *   or call GWPlayerCoinSet 0x80045514 / GWPlayerCoinAdd 0x800455C4
 *
 * Generated by asm/mp8/tools/boardbase.py -- do not edit by hand.
 */
#define MP8_OMCUROVL      0x802CDD1C  /* s32, _ovltbl index of the live overlay */
#define MP8_ROULETTE_ORIG 0x801E002C  /* lwz r0,0x2C(r30) */
#define MP8_MGCALL_ORIG   0x38800061  /* li r4,97 -- mginstdll */
#define MP8_GWPLAYER      0x802282F8  /* GW_PLAYER[4], stride 0x118 */
#define MP8_GWPLAYER_SIZE 0x118
#define MP8_GWPLAYER_COIN 0x26        /* s16 */
